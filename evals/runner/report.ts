/**
 * Renders the recorded runs into `docs/reference/eval-results.md` and a
 * pasteable console block, in the same shape as the contract suite's report.
 *
 * The table that matters is the round-trip ledger. RFC-003 "Honest
 * Trade-offs" claims 2-3 round-trips to a first write against the typed
 * surface's 1, and says the cost "should be measured, not assumed". This is
 * the measurement, so it gets its own section and is printed even when every
 * task passes.
 */

import type { RecordedRun } from "./observations.js";

export interface EvalReportMeta {
  generatedAt: string;
  /** Redacted unless NETBOX_EVAL_INCLUDE_HOST=1. */
  instance: string;
  netboxVersion: string;
  tokenCapability: string;
  mode: string;
  outcome: string;
}

const MARKER: Record<string, string> = {
  pass: "PASS",
  fail: "FAIL",
  unverified: "N/A",
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function tally(runs: readonly RecordedRun[]): Record<string, number> {
  const counts: Record<string, number> = { pass: 0, fail: 0, unverified: 0 };
  for (const run of runs) counts[run.verdict] = (counts[run.verdict] ?? 0) + 1;
  return counts;
}

/** The tasks whose sequence ends in a write; the RFC's claim is about these. */
function writeTasks(runs: readonly RecordedRun[]): RecordedRun[] {
  return runs.filter((run) => run.calls.some((call) => call.tool === "netbox_write"));
}

function callLine(run: RecordedRun): string {
  return run.calls.map((call) => `${call.tool}${call.simulated ? "*" : ""}`).join(" -> ");
}

export function renderMarkdown(
  runs: readonly RecordedRun[],
  meta: EvalReportMeta,
): string {
  const counts = tally(runs);
  const writes = writeTasks(runs);
  const lines: string[] = [
    "# Eval results — NetBox MCP layered tool surface",
    "",
    "Generated by `npm run eval` (`evals/`). **Do not hand-edit:** the next run",
    "overwrites this file. Commit it when the numbers change.",
    "",
    "Each row is a task from `evals/tasks.ts`: a request a user would make, the",
    "reference tool-call sequence for it, and whether that sequence works on this",
    "instance. A `FAIL` row means the reference path is broken or the surface does",
    "not support the task — **not** that a model chose badly. Nothing here scores a",
    'model\'s choices; see `evals/README.md`, "What this cannot score".',
    "",
    "## Run",
    "",
    "|            |            |",
    "| ---------- | ---------- |",
    `| Generated  | ${escapeCell(meta.generatedAt)} |`,
    `| Instance   | ${escapeCell(meta.instance)} |`,
    `| NetBox     | ${escapeCell(meta.netboxVersion)} |`,
    `| Token      | ${escapeCell(meta.tokenCapability)} |`,
    `| Mode       | ${escapeCell(meta.mode)} |`,
    `| Outcome    | ${escapeCell(meta.outcome)} |`,
    "",
    `**${counts["fail"] ?? 0} failed**, ${counts["pass"] ?? 0} passed, ` +
      `${counts["unverified"] ?? 0} not verifiable on this instance ` +
      `— ${runs.length} task(s).`,
    "",
    "## Round-trip ledger",
    "",
    "The number RFC-003 said should be measured rather than assumed. A round-trip",
    "is one tool call the model has to make; a call marked `*` was simulated, and",
    "is counted, because a model would still have had to make it.",
    "",
    "| Task | Failure mode | Round-trips | Budget | Sequence |",
    "| ---- | ------------ | ----------- | ------ | -------- |",
    ...runs.map(
      (run) =>
        `| ${run.id} | ${escapeCell(run.failureMode)} | ${run.roundTrips} | ${run.roundTripBudget} | ${escapeCell(callLine(run))} |`,
    ),
    "",
    `Total: ${runs.reduce((sum, run) => sum + run.roundTrips, 0)} round-trip(s) across ` +
      `${runs.length} task(s), against a budget of ` +
      `${runs.reduce((sum, run) => sum + run.roundTripBudget, 0)}.`,
    "",
  ];

  if (writes.length > 0) {
    lines.push(
      "**Round-trips to a first write** — the row RFC-003 puts at 2-3 against the",
      "typed surface's 1:",
      "",
      "| Task | Calls before the write | Total |",
      "| ---- | ---------------------- | ----- |",
      ...writes.map((run) => {
        const first = run.calls.findIndex((call) => call.tool === "netbox_write");
        return `| ${run.id} | ${first < 0 ? "n/a" : first} | ${run.roundTrips} |`;
      }),
      "",
    );
  }

  lines.push("## Tasks", "");
  for (const run of runs) {
    lines.push(
      `### ${MARKER[run.verdict] ?? run.verdict} — ${run.id}. ${run.title}`,
      "",
      `> ${run.request}`,
      "",
      `- **Probes:** ${run.probes}`,
      `- **Failure mode:** \`${run.failureMode}\``,
      `- **Reference sequence:** ${run.expectedSequence}`,
      `- **Success condition:** ${run.successCondition}`,
      `- **Scoreable here:** ${run.judgement}`,
      `- **Round-trips:** ${run.roundTrips} (${run.executedCalls} sent, ${run.simulatedCalls} simulated), budget ${run.roundTripBudget}`,
      `- **Outcome:** ${run.detail}`,
      ...(run.firstWrongStep === undefined
        ? []
        : [`- **First went wrong at:** step ${run.firstWrongStep}`]),
      `- **A wrong path looks like:** ${run.plausibleWrongPath}`,
      "",
      "| # | Tool | Arguments | Result |",
      "| - | ---- | --------- | ------ |",
      ...run.calls.map(
        (call) =>
          `| ${call.index}${call.simulated ? "*" : ""} | ${call.tool} | ${escapeCell(
            JSON.stringify(call.args).slice(0, 220),
          )} | ${escapeCell(call.head)} |`,
      ),
      "",
    );
    const bad = run.steps.filter((step) => !step.ok);
    if (bad.length > 0) {
      lines.push(
        ...bad.map((step) => `- Step ${step.step} (${step.label}): ${step.detail}`),
        "",
      );
    }
  }

  const needsJudgement = runs.filter((run) => run.judgement !== "mechanical");
  lines.push(
    "## Not settled by this run",
    "",
    "These tasks have a half no runner can decide. The rows above establish the",
    "ground truth — that the reference path works, or that the surface genuinely",
    "cannot do the thing — and a human or an LLM judge decides whether a model",
    "behaved correctly against it.",
    "",
    "| Task | Needs | The question a judge has to answer |",
    "| ---- | ----- | ---------------------------------- |",
    ...needsJudgement.map(
      (run) => `| ${run.id} | ${run.judgement} | ${escapeCell(run.plausibleWrongPath)} |`,
    ),
    "",
    "---",
    "",
    "Re-run with:",
    "",
    "```sh",
    "NETBOX_URL=https://netbox.example.com \\",
    "NETBOX_TOKEN=<token> \\",
    "npm run eval",
    "```",
    "",
  );

  return lines.join("\n");
}

export const BLOCK_BEGIN = "===== NETBOX EVAL REPORT BEGIN =====";
export const BLOCK_END = "===== NETBOX EVAL REPORT END =====";

export function renderConsoleBlock(
  runs: readonly RecordedRun[],
  meta: EvalReportMeta,
): string {
  const counts = tally(runs);
  const lines: string[] = [
    BLOCK_BEGIN,
    `instance    : ${meta.instance}`,
    `netbox      : ${meta.netboxVersion}`,
    `mode        : ${meta.mode}`,
    `outcome     : ${meta.outcome}`,
    `tasks       : ${runs.length} — ${counts["fail"] ?? 0} FAIL, ${counts["pass"] ?? 0} PASS, ` +
      `${counts["unverified"] ?? 0} N/A`,
    "",
  ];
  for (const run of runs) {
    lines.push(
      `  [${(MARKER[run.verdict] ?? "?").padEnd(4)}] ${run.id} ${run.title}`,
      `           round-trips: ${run.roundTrips} (budget ${run.roundTripBudget})`,
      `           sequence   : ${callLine(run)}`,
      `           outcome    : ${run.detail}`,
    );
  }
  lines.push("", BLOCK_END);
  return lines.join("\n");
}
